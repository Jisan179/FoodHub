<article class="card prose">
    <h1>Privacy policy</h1>
    <p>This page describes what this demonstration application stores and who can see it. Do not enter sensitive or real payment information.</p>
    <h2>What is stored</h2>
    <ul>
        <li>Account details: name, username, email, phone, address and a hash of your password</li>
        <li>Activity: cart, favorites, orders, delivery records and reviews</li>
        <li>Security records: recent sign-in and password reset attempts, stored as hashed keys</li>
    </ul>
    <h2>Who can see it</h2>
    <ul>
        <li>A restaurant manager sees the name, delivery address and contact phone for orders from their restaurant.</li>
        <li>A rider sees the customer's name, address and contact phone only after accepting that delivery.</li>
        <li>Administrators can see accounts and orders.</li>
    </ul>
    <h2>Cookies and other services</h2>
    <p>One session cookie keeps you signed in. The application sets no advertising or analytics cookies. Fonts are loaded from Google Fonts, so your browser contacts Google when a page loads. A delivery address is sent to Google Maps only when a rider chooses "Open in Google Maps".</p>
    <h2>Your choices</h2>
    <p>You can edit your details or deactivate your account from your profile. An account without order history can also be deleted.</p>
