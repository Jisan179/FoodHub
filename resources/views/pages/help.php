<article class="card prose">
    <h1>Help centre</h1>
    <h2>How do I place an order?</h2>
    <p>Sign in as a customer, open a restaurant, add dishes to your cart and go to checkout. A cart can hold dishes from one restaurant at a time.</p>
    <h2>Can I cancel an order?</h2>
    <p>Yes, while it is Pending or Preparing. Open the order from "My Orders" and choose "Cancel order".</p>
    <h2>I forgot my password</h2>
    <p>Use "Forgot your password?" on the sign-in page. The emailed link works once and expires after 30 minutes. In local development the message is written to the mail log instead of being sent.</p>
    <h2>Why can't I sign in to my new restaurant or rider account?</h2>
    <p>Restaurant Manager and Rider accounts must be approved by an administrator first.</p>
    <h2>When can I review a dish?</h2>
    <p>After the order has been delivered. Open "Reviews" and tap the stars.</p>
    <h2>Still need help?</h2>
    <p>Contact the administrator of this FoodHub installation.</p>
